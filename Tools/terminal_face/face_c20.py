# ------------------------------------------------------------------ CP437 additions (41 section 6.1), full 16-row cells
def cell(rows):
    out = ['........'] * 16
    for r, s in rows.items():
        out[r] = s
    return out


def vline(top, bottom):
    return {r: '...##...' for r in range(top, bottom + 1)}


def merge(*parts):
    rows = {}
    for p in parts:
        for r, s in p.items():
            old = rows.get(r, '........')
            rows[r] = ''.join('#' if a == '#' or b == '#' else '.' for a, b in zip(old, s))
    return rows


