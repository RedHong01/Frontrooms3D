NEED = list(range(0x21, 0x7F)) + [0xC4, 0xB3, 0xDA, 0xBF, 0xC0, 0xD9, 0xC3, 0xB4, 0xDB, 0x18, 0x19, 0x1B, 0x1A, 0xFE]


def glyph_cell(code):
    """16 strings of 8 for a code (blank if not drawn)."""
    if code in CP437:
        return CP437[code]
    ch = chr(code) if 0x20 <= code <= 0x7E else None
    if ch is None or ch not in G:
        return ['........'] * 16
    rows = ['........'] * 16
    for i, r in enumerate(G[ch]):
        rows[CAP_TOP + i] = (r + '........')[:8]
    return rows


def build():
    im = Image.new('RGB', (128, 320), (0, 0, 0))
    px = im.load()
    for code in range(256):
        cx, cy = (code % 16) * 8, (code // 16) * 16
        for y, row in enumerate(glyph_cell(code)):
            for x, v in enumerate(row):
                if v == '#':
                    px[cx + x, cy + y] = (255, 255, 255)
    for base, abc in ((256, BIG), (288, SMALL)):
        for ch, spec in abc.items():
            k = ord(ch) - 0x20
            cx, cy = (k % 16) * 8, base + (k // 16) * 8
            for r, line in enumerate(spec.split('/')):
                for c, v in enumerate(line):
                    if v == '#':
                        px[cx + c, cy + r] = (255, 255, 255)
    return im


# ------------------------------------------------------------------ checks (metrics + coverage)
ASC = set('bdfhkl') | set('ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789')
DESC = set('gjpqy')
TALL = set('()[]{}/\\|$Q,;')   # allowed below the baseline (and $ / brackets span the cap line)


def check():
    problems = []
    for ch, rows in G.items():
        for i, r in enumerate(rows):
            if len(r) not in (7, 8):
                problems.append(f'{ch!r} row {CAP_TOP + i}: width {len(r)}')
            if len(r) == 8 and r[7] == '#' and ch != '_':
                problems.append(f'{ch!r} row {CAP_TOP + i}: ink in column 7')
        ink_rows = [CAP_TOP + i for i, r in enumerate(rows) if '#' in r]
        if not ink_rows:
            problems.append(f'{ch!r}: empty')
            continue
        lo, hi = min(ink_rows), max(ink_rows)
        if ch.isalpha() and ch.isupper() or ch.isdigit():
            if (lo, hi) != (CAP_TOP, BASE) and ch != 'Q':
                problems.append(f'{ch!r}: rows {lo}-{hi}, caps/figures need {CAP_TOP}-{BASE}')
        elif ch.islower():
            want_lo = CAP_TOP if ch in ASC or ch in 'ij' else (3 if ch == 't' else X_TOP)
            want_hi = DESC_END if ch in DESC else BASE
            if (lo, hi) != (want_lo, want_hi):
                problems.append(f'{ch!r}: rows {lo}-{hi}, want {want_lo}-{want_hi}')
        if hi > BASE and ch not in DESC and ch not in TALL and ch != '_':
            problems.append(f'{ch!r}: below the baseline (row {hi})')
    drawn = [c for c in range(256) if any('#' in r for r in glyph_cell(c))]
    missing = [hex(c) for c in NEED if c not in drawn]
    if missing:
        problems.append('missing ' + ', '.join(missing))
    for name, abc, (w, h) in (('BIG', BIG, (5, 7)), ('SMALL', SMALL, (4, 5))):
        for ch, spec in abc.items():
            rows = spec.split('/')
            if len(rows) != h or any(len(r) != w for r in rows):
                problems.append(f'{name} {ch!r}: not {w} x {h}')
    return drawn, problems


