    const string WrapKit = "Kit_WrapFixture_4ft", WrapLensSlot = "Run_WrapLens", WrapLensPath = "Wrap/Materials/ZL_WrapLens_R1";

    sealed class Kit
    {
        public string folder, model, desktopPrefab, phonePrefab;
        /// <summary>A second renderer the caller drives apart from the lens: the child of that name in the phone prefab gives its
        /// material and phone mesh, the model's mesh of that name its desktop mesh (the pendant's "Glow", the strip's "LensRed").
        /// Required for the pendant (its patch is part of the look); optional for the strip (an older kit builds without it).</summary>
        public string second, secondSuffix;
        public bool secondRequired, secondAdditive;
        public bool loaded, ok, desktopLoaded, desktopOk;
        public Mesh lensMesh, phoneMesh, secondMesh, secondPhoneMesh;
        public Material lensMaterial, secondMaterial;
        public GameObject housingSource;
    }

    static Kit[] kits;
    static bool warned, wrapLoaded, wrapOk;
    static Mesh wrapDesktop, wrapPhone;
    static Material[] wrapDesktopMaterials, wrapPhoneMaterials;

    [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.SubsystemRegistration)]
    static void ResetStatics()
    {
        kits = null;
        warned = wrapLoaded = wrapOk = false;
        wrapDesktop = wrapPhone = null;
        wrapDesktopMaterials = wrapPhoneMaterials = null;
    }

    static Kit Get(Family family)
    {
        if (kits == null)
            kits = new[]
            {
                new Kit { folder = "Strip/", model = "Models/ZL_STRIP", desktopPrefab = "Prefabs/ZL_STRIP", phonePrefab = "Prefabs/ZL_STRIP_Phone",
                          second = "LensRed", secondSuffix = " red" },
                new Kit { folder = "RemotePlate/", desktopPrefab = "Prefabs/ZL_RPLATE" },
                new Kit { folder = "Pendant/", model = "Models/ZL_PEND", desktopPrefab = "Prefabs/ZL_PEND", phonePrefab = "Prefabs/ZL_PEND_Phone",
                          second = GlowName, secondSuffix = " glow", secondRequired = true, secondAdditive = true },
                null,   // Wrap: the kit library's Kit_WrapFixture_4ft (LoadWrap)
                new Kit { folder = "WallBox/", model = "Models/ZL_WALLBOX", desktopPrefab = "Prefabs/ZL_WALLBOX", phonePrefab = "Prefabs/ZL_WALLBOX_Phone",
                          second = GlowName, secondSuffix = " glow", secondRequired = true, secondAdditive = true },
                new Kit { folder = "Niche/", model = "Models/ZL_NICHE", desktopPrefab = "Prefabs/ZL_NICHE", phonePrefab = "Prefabs/ZL_NICHE_Phone" },
                new Kit { folder = "NicheSmall/", model = "Models/ZL_NICHE_S", desktopPrefab = "Prefabs/ZL_NICHE_S", phonePrefab = "Prefabs/ZL_NICHE_S_Phone" },
                new Kit { folder = "Flush/", model = "Models/ZL_FLUSH", desktopPrefab = "Prefabs/ZL_FLUSH", phonePrefab = "Prefabs/ZL_FLUSH_Phone" },
                new Kit { folder = "Globe/", model = "Models/ZL_GLOBE", desktopPrefab = "Prefabs/ZL_GLOBE", phonePrefab = "Prefabs/ZL_GLOBE_Phone" },
                new Kit { folder = "WallPack/", model = "Models/ZL_WALLPACK", desktopPrefab = "Prefabs/ZL_WALLPACK", phonePrefab = "Prefabs/ZL_WALLPACK_Phone" },
                new Kit { folder = "DockArm/", model = "Models/ZL_DOCKARM", desktopPrefab = "Prefabs/ZL_DOCKARM", phonePrefab = "Prefabs/ZL_DOCKARM_Phone" },
            };
        var i = (int)family;
        return i >= 0 && i < kits.Length ? kits[i] : null;
    }

    /// <summary>The phone tier, as the troffer's (handheld, the lab's DebugForcePhoneTier, WebGL players).</summary>
    public static bool PhoneTier => FrontRoomsTrofferKit.PhoneTier;

    /// <summary>The family's assets are in the build. False: the caller builds what it built before.</summary>
    public static bool Available(Family family)
    {
        if (family == Family.Wrap) return LoadWrap();
        var k = Get(family);
        return k != null && (k.phonePrefab == null ? LoadDesktop(k) : Load(k));
    }

    /// <summary>The family's lens material (FrontRooms/Surface, _EMISSION); null when missing or for a housing-only family.</summary>
    public static Material LensMaterial(Family family)
    {
        if (family == Family.Wrap) return LoadWrap() ? Resources.Load<Material>(ResourceRoot + WrapLensPath) : null;
        var k = Get(family);
        return k != null && k.phonePrefab != null && Load(k) ? k.lensMaterial : null;
    }

    // Every tier: the lens material and its maps (through the phone prefab, which holds nothing else but the glow) and the
    // model's meshes (the FBX imports no material). The desktop prefab, which pulls in the trim sheet, is loaded only by the
    // first build that needs a housing, so a phone lamp never holds the trim's textures.
    static bool Load(Kit k)
    {
        if (k.loaded) return k.ok;
        k.loaded = true;
        var phone = Resources.Load<GameObject>(ResourceRoot + k.folder + k.phonePrefab);
        var phoneLens = phone != null ? phone.transform.Find(LensName) : null;
        var phoneRenderer = phoneLens != null ? phoneLens.GetComponent<MeshRenderer>() : null;
        var phoneFilter = phoneLens != null ? phoneLens.GetComponent<MeshFilter>() : null;
        k.lensMaterial = phoneRenderer != null ? phoneRenderer.sharedMaterial : null;
        k.phoneMesh = phoneFilter != null ? phoneFilter.sharedMesh : null;
        if (k.second != null)
        {
            var second = phone != null ? phone.transform.Find(k.second) : null;
            var secondRenderer = second != null ? second.GetComponent<MeshRenderer>() : null;
            var secondFilter = second != null ? second.GetComponent<MeshFilter>() : null;
            k.secondMaterial = secondRenderer != null ? secondRenderer.sharedMaterial : null;
            k.secondPhoneMesh = secondFilter != null ? secondFilter.sharedMesh : null;
        }
        foreach (var m in Resources.LoadAll<Mesh>(ResourceRoot + k.folder + k.model))
        {
            if (m == null) continue;
            if (m.name == LensName) k.lensMesh = m;
            else if (k.second != null && m.name == k.second) k.secondMesh = m;
        }
        var hasSecond = k.secondMesh != null && k.secondPhoneMesh != null && k.secondMaterial != null;
        if (!hasSecond) k.secondMesh = k.secondPhoneMesh = null;
        k.ok = k.lensMesh != null && k.phoneMesh != null && k.lensMaterial != null && (!k.secondRequired || hasSecond);
        if (!k.ok) Warn(k.folder + k.phonePrefab + ", " + k.folder + k.model);
        return k.ok;
    }

    static bool LoadDesktop(Kit k)
    {
        if (k.desktopLoaded) return k.desktopOk;
        k.desktopLoaded = true;
        var desktop = Resources.Load<GameObject>(ResourceRoot + k.folder + k.desktopPrefab);
        // A lamp's prefab holds its lens (and its second renderer) and its housing; a housing-only family's prefab is the housing.
        var housing = desktop == null ? null : k.phonePrefab != null ? desktop.transform.Find(HousingName) : desktop.transform;
        k.housingSource = housing != null && housing.GetComponent<LODGroup>() != null ? housing.gameObject : null;
        k.desktopOk = k.housingSource != null;
        if (!k.desktopOk) Warn(k.folder + k.desktopPrefab);
        return k.desktopOk;
    }

    // Lo-C: the kit library builds one Kit_WrapFixture_4ft (its materials by slot, as everywhere), the LOD0 and LOD2 meshes and
    // their material sets are kept with the lens slot on ZL_WrapLens_R1, and the probe goes before it is ever drawn.
    static bool LoadWrap()
    {
        if (wrapLoaded) return wrapOk;
        wrapLoaded = true;
        var lens = Resources.Load<Material>(ResourceRoot + WrapLensPath);
        var probe = lens != null ? FrontRoomsKitLibrary.Spawn(WrapKit, null, Vector3.zero, Quaternion.identity, null, false, "zone lamps wrap probe", false) : null;
        if (probe != null)
        {
            probe.SetActive(false);
            foreach (var r in probe.GetComponentsInChildren<MeshRenderer>(true))
            {
                var mf = r.GetComponent<MeshFilter>();
                var mesh = mf != null ? mf.sharedMesh : null;
                if (mesh == null) continue;
                if (mesh.name.EndsWith("_LOD0")) { wrapDesktop = mesh; wrapDesktopMaterials = WithLens(r.sharedMaterials, lens); }
                else if (mesh.name.EndsWith("_LOD2")) { wrapPhone = mesh; wrapPhoneMaterials = WithLens(r.sharedMaterials, lens); }
            }
            if (Application.isPlaying) Object.Destroy(probe);
            else Object.DestroyImmediate(probe);
        }
        wrapOk = wrapDesktop != null && wrapPhone != null && wrapDesktopMaterials != null && wrapPhoneMaterials != null;
        if (!wrapOk) Warn(WrapKit + ", " + WrapLensPath);
        return wrapOk;
    }

    static Material[] WithLens(Material[] set, Material lens)
    {
        var found = false;
        var copy = new Material[set.Length];
        for (var i = 0; i < set.Length; i++)
        {
            var m = set[i];
            if (m != null && m.name.StartsWith(WrapLensSlot, System.StringComparison.Ordinal)) { copy[i] = lens; found = true; }
            else copy[i] = m;
        }
        return found ? copy : null;
    }

    static void Warn(string what)
    {
        if (warned) return;
        warned = true;
        Debug.LogWarning("[FrontRoomsLampKit] Resources/" + ResourceRoot + " is incomplete (" + what + "): the lamps keep the landed kit.");
    }

    /// <summary>
    /// Builds a lamp of <paramref name="family"/> under <paramref name="parent"/> at <paramref name="position"/> /
    /// <paramref name="rotation"/> (its mounting face and axis, parent space): the lens (returned, named
    /// <paramref name="lensName"/>) and, unless <paramref name="phone"/>, the housing. Returns null and builds nothing when
    /// the kit is missing (or for a housing-only family: BuildHousing). Nothing is lit here.
    /// </summary>
    public static MeshRenderer Build(Family family, Transform parent, Vector3 position, Quaternion rotation, string lensName, bool phone)
    {
        return Build(family, parent, position, rotation, lensName, phone, out _);
    }

    /// <summary>As Build; a family with a second renderer also builds it, returned in <paramref name="second"/> (null for the
    /// others): the pendant's glow ("&lt;lensName&gt; glow", the caller writes it the lens's block), the strip's red tube
    /// ("&lt;lensName&gt; red", the caller drives its own level).</summary>
    public static MeshRenderer Build(Family family, Transform parent, Vector3 position, Quaternion rotation, string lensName, bool phone, out MeshRenderer second)
    {
        second = null;
        var name = string.IsNullOrEmpty(lensName) ? LensName : lensName;
        if (family == Family.Wrap)
        {
            if (parent == null || !LoadWrap()) return null;
            // The kit's long axis is X; turn it to run along the lamp's Z.
            var wrap = Part(parent, name, phone ? wrapPhone : wrapDesktop, phone ? wrapPhoneMaterials : wrapDesktopMaterials, position, rotation * Quaternion.Euler(0f, 90f, 0f));
            // the Relay's body reads the lamps it presses under (research/hunter/production_b/40_ceiling_lamps.md)
            FrontRoomsTrofferKit.RegisterLamp(wrap, parent.TransformPoint(position).y, FrontRoomsTrofferKit.LampShape.Wrap, null, parent);
            return wrap;
        }
        var k = Get(family);
        if (parent == null || k == null || k.phonePrefab == null || !Load(k)) return null;
        if (!phone && !LoadDesktop(k)) return null;
        var lens = Part(parent, name, phone ? k.phoneMesh : k.lensMesh, new[] { k.lensMaterial }, position, rotation);
        var secondMesh = phone ? k.secondPhoneMesh : k.secondMesh;
        if (secondMesh != null)
        {
            second = Part(parent, name + k.secondSuffix, secondMesh, new[] { k.secondMaterial }, position, rotation);
            if (k.secondAdditive)
            {
                second.lightProbeUsage = LightProbeUsage.Off;
                second.reflectionProbeUsage = ReflectionProbeUsage.Off;
            }
        }
        var housing = phone ? null : Housing(k, parent, position, rotation);
        // a pendant hangs into the Relay's reach: its body registers with the lens (the glow never does; 40_ceiling_lamps.md)
        if (family == Family.Pendant)
            FrontRoomsTrofferKit.RegisterLamp(lens, parent.TransformPoint(position).y, FrontRoomsTrofferKit.LampShape.Pendant,
                housing != null ? housing.GetComponentsInChildren<Renderer>(true) : null, parent);
        // so does the Run! strip, a surface lamp like the wrap: its guard hangs 117 mm under the soffit on the corridor's axis,
        // where a trip calls the Relay (the red tube never registers; no "Light" beside it, so the body folds; the Run! rig hands its
        // strip Light over, FrontRoomsTrofferKit.SetLampLight, so the contact takes it: white armed, red under the alarm, card 3)
        else if (family == Family.Strip)
            FrontRoomsTrofferKit.RegisterLamp(lens, parent.TransformPoint(position).y, FrontRoomsTrofferKit.LampShape.Wrap,
                housing != null ? housing.GetComponentsInChildren<Renderer>(true) : null, parent);
        return lens;
    }

    /// <summary>
    /// P1-A's wall box under <paramref name="parent"/>: <paramref name="position"/> is its mounting centre on the wall,
    /// <paramref name="rotation"/> turns local +Z out of the wall and +Y up. Its lit ceiling (<paramref name="glow"/>, the second
    /// renderer) is fitted to the ceiling <paramref name="ceilingAbove"/> metres over the mount: 2 mm under it, WallBoxGlowSpread
    /// times that throw along the wall and out from it. The caller lights it and writes the glow the lens's block, as the
    /// pendant's. Returns the lens; null when the kit is missing (the caller builds what it built before).
    /// </summary>
    public static MeshRenderer BuildWallBox(Transform parent, Vector3 position, Quaternion rotation, string lensName, bool phone, float ceilingAbove, out MeshRenderer glow)
    {
        var lens = Build(Family.WallBox, parent, position, rotation, lensName, phone, out glow);
        if (lens != null && glow != null)
        {
            var d = Mathf.Max(.3f, ceilingAbove);
            var t = glow.transform;
            t.localPosition = position + rotation * new Vector3(0f, d - .002f, 0f);
            t.localScale = new Vector3(WallBoxGlowSpread * d, 1f, WallBoxGlowSpread * d);
        }
        return lens;
    }

    static MeshRenderer Part(Transform parent, string name, Mesh mesh, Material[] materials, Vector3 position, Quaternion rotation)
