using FrontRooms.Map;
using UnityEngine;
using UnityEngine.Rendering;

/// <summary>
/// The zone lamps (line zone_lamps, research/zone_lamps; Red 2026-10-31 picked a lamp per zone): one factory for the lamp
/// families past Level 0's L03 troffer. L03 stays FrontRoomsTrofferKit's (the map's Level 0, Low and Tall rooms, the start
/// room, the title corridor, the station); every family here keeps its rules: the lens renderer carries every glowing part
/// of the fixture, the caller drives its _EmissionColor exactly as it drove the lamp it replaces (flicker, dim, dead, the
/// warning bursts, the blackout), nothing is lit here, shadows off, no colliders. Kits: Resources/Props/Lamps/&lt;Family&gt;/
/// (Models, Materials, Textures, Prefabs), generated by zone_lamps/kit/zl_build.py and zl_tex.py; the housings sit on the
/// troffer's trim sheet (Props/Troffer/Materials/Troffer_Trim), so a family adds no trim texture.
///
///   Strip        Run! armed (Red 10-31 picked R-B on the run_armed sheet): a bare 4 ft strip, T12 tubes under a white
///                enamel channel, a zinc wire guard (ZL_STRIP; 1990 service corridors, research/zone_lamps/10_run.md F2 + F4).
///                Since 11-04 (Red said yes to the red tube at the BRIGHTEST level, card zone_lamps 1) a three-lamp strip,
///                channel 140 mm: the middle tube is red-coated on the battery circuit (research/level_space/71_run_room.md
///                s.6.2). Lens = the two white tubes (64 tris), the renderer the lamp logic drives: a dead or stuttering tube
///                shows itself, ends and all; the red tube is the second renderer ("&lt;lens&gt; red", 32 tris, ZL_STRIP_Red:
///                oxblood, no emission of its own), driven apart (FrontRoomsRunRig). Housing = channel, lampholders, tube
///                bases and the guard, desktop only (LODGroup 2362 / 874 / 14 tris, 4 m / 12 m, culled at 46 m). Phone tier:
///                the phone mesh (42 tris: the white tubes and the channel in an emission-free swatch) and the red tube's
///                (16 tris), no housing: two draws.
///   RemotePlate  Run! tripped (Red 10-31: T-A and T-B combined, on the run_tripped sheet): the T-B remote mount that holds a
///                twin-head unit's two heads where no cabinet is, a 4 in octagon box on the wall under a formed bracket and a
///                stem (ZL_RPLATE, LODGroup 136 / 78 / 38 tris). Built in the twin-head cabinet's own frame
///                (Kit_EmergencyTwinHead: wall at z 0, the yokes on the same mount_l / mount_r), so it takes the cabinet's
///                place one for one. No glow, every tier (two per corridor: the trim sheet is the only texture).
///   Pendant      Office floors (Red 10-31 picked O-C on the office sheet): an 8 ft lensed-indirect pendant, its body's bottom
///                0.60 m under the ceiling plane (2.30 m in a 2.9 m room) on two aircraft cables (ZL_PEND; the 1987 lensed-
///                indirect patents, the Cornell 1989-90 field study, 10_office.md F4). Lens = the side lens strips and the top
///                lens (6 tris; phone: 18 with the body in an enamel swatch); Glow = the lit ceiling over it, a 3.4 x 2.2 m quad
///                2 mm under the ceiling plane on FrontRooms/LampGlow (additive, analytic, no texture) as its OWN renderer (the
///                second renderer) "&lt;lens&gt; glow" whose only material is transparent, so GlassRT never traces it; the caller writes it the
///                lens's block (MapWorld: TickFixtures / WriteEmission), so a dead lamp leaves a dark patch of ceiling.
///                Housing = the extruded body, end caps, cables, canopies and cord (LODGroup 770 / 322 / 90 tris, desktop
///                only). Draws: desktop 3, phone 2. Lens drive PendantLensPeak (1.4, the render's).
///   Wrap         Low back-of-house modules (Red 10-31: "low zones as recommended", Lo-C): the Run! B / stairwell 4 ft
///                wraparound (Kit_WrapFixture_4ft, in main) surface-mounted on the grid as ONE renderer, its LOD0 mesh on
///                desktop and its LOD2 on phones (a LOD copy would never get the lamp's level), the kit's own materials with
///                the lens slot on ZL_WrapLens_R1 (the landed Run_WrapLens with the R1 emission map: dim cathode ends, as the
///                Low sheet showed it). Lens drive WrapLensPeak (1.8, L03's level).
///
/// The map (BuildFixture) asks ForCell for its cell's lamp and builds it with BuildMapLamp under the fixture root, on the
/// ceiling plane, long side along the root's Z; the lens is named "Lens" (a direct child, beside "Light" for GlassRT).
/// A family's mounting face is its local y 0; long axis along local Z. Names avoid "Light", floor, carpet, ceiling, wall,
/// seal and partition (RoomStream.RefreshRoomMaterials). ASCII only.
/// </summary>
public static class FrontRoomsLampKit
{
    public enum Family : byte { Strip, RemotePlate, Pendant, Wrap }

    /// <summary>What the map hangs at a cell (ForCell, BuildMapLamp, LensDrive).</summary>
    public enum MapLamp : byte { Troffer, Pendant, Wrap }

    public const string ResourceRoot = "Props/Lamps/";
    public const string LensName = "Lens", HousingName = "Housing", GlowName = "Glow";
    /// <summary>The strip's length along its axis, lampholders included (the channel is 1.27 m): what a ceiling item clears.</summary>
    public const float StripHalfLength = .64f;
    /// <summary>O-C's lens as seen (the option render's drive, gamma as passed); its ceiling patch rides the same drive at the
    /// glow material's _Gain (0.42).</summary>
    public const float PendantLensPeak = 1.4f;
    /// <summary>Lo-C's lens as seen (the option render's drive: L03's 1.8).</summary>
    public const float WrapLensPeak = 1.8f;
    /// <summary>O-C hangs its body's bottom this far under the ceiling plane (a 0.10 m body on 0.50 m cables) and only where that
    /// bottom stays at or above PendantMinBottom: the 2.9 m Office rooms (2.30 m), never a Low one (the 2.03 m headroom clause).</summary>
    public const float PendantDrop = .60f, PendantMinBottom = 2.2f;
    const string WrapKit = "Kit_WrapFixture_4ft", WrapLensSlot = "Run_WrapLens", WrapLensPath = "Wrap/Materials/ZL_WrapLens_R1";

    sealed class Kit
    {
        public string folder, model, desktopPrefab, phonePrefab;
        /// <summary>A second renderer the caller drives apart from the lens: the child of that name in the phone prefab gives its
        /// material and phone mesh, the model's mesh of that name its desktop mesh (the pendant's "Glow", the strip's "LensRed").
        /// Required for the pendant (its patch is part of the look); optional for the strip (an older kit builds without it).</summary>
        public string second, secondSuffix;
        public bool secondRequired, secondAdditive;
        public bool loaded, ok, desktopLoaded, desktopOk;
        public Mesh lensMesh, phoneMesh, secondMesh, secondPhoneMesh;
        public Material lensMaterial, secondMaterial;
        public GameObject housingSource;
    }

    static Kit[] kits;
    static bool warned, wrapLoaded, wrapOk;
    static Mesh wrapDesktop, wrapPhone;
    static Material[] wrapDesktopMaterials, wrapPhoneMaterials;

    [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.SubsystemRegistration)]
    static void ResetStatics()
    {
        kits = null;
        warned = wrapLoaded = wrapOk = false;
        wrapDesktop = wrapPhone = null;
        wrapDesktopMaterials = wrapPhoneMaterials = null;
    }

    static Kit Get(Family family)
    {
        if (kits == null)
            kits = new[]
            {
                new Kit { folder = "Strip/", model = "Models/ZL_STRIP", desktopPrefab = "Prefabs/ZL_STRIP", phonePrefab = "Prefabs/ZL_STRIP_Phone",
                          second = "LensRed", secondSuffix = " red" },
                new Kit { folder = "RemotePlate/", desktopPrefab = "Prefabs/ZL_RPLATE" },
                new Kit { folder = "Pendant/", model = "Models/ZL_PEND", desktopPrefab = "Prefabs/ZL_PEND", phonePrefab = "Prefabs/ZL_PEND_Phone",
                          second = GlowName, secondSuffix = " glow", secondRequired = true, secondAdditive = true },
                null,   // Wrap: the kit library's Kit_WrapFixture_4ft (LoadWrap)
            };
        var i = (int)family;
        return i >= 0 && i < kits.Length ? kits[i] : null;
    }

    /// <summary>The phone tier, as the troffer's (handheld, the lab's DebugForcePhoneTier, WebGL players).</summary>
    public static bool PhoneTier => FrontRoomsTrofferKit.PhoneTier;

    /// <summary>The family's assets are in the build. False: the caller builds what it built before.</summary>
    public static bool Available(Family family)
    {
        if (family == Family.Wrap) return LoadWrap();
        var k = Get(family);
        return k != null && (k.phonePrefab == null ? LoadDesktop(k) : Load(k));
    }

    /// <summary>The family's lens material (FrontRooms/Surface, _EMISSION); null when missing or for a housing-only family.</summary>
    public static Material LensMaterial(Family family)
    {
        if (family == Family.Wrap) return LoadWrap() ? Resources.Load<Material>(ResourceRoot + WrapLensPath) : null;
        var k = Get(family);
        return k != null && k.phonePrefab != null && Load(k) ? k.lensMaterial : null;
    }

    // Every tier: the lens material and its maps (through the phone prefab, which holds nothing else but the glow) and the
    // model's meshes (the FBX imports no material). The desktop prefab, which pulls in the trim sheet, is loaded only by the
    // first build that needs a housing, so a phone lamp never holds the trim's textures.
    static bool Load(Kit k)
    {
        if (k.loaded) return k.ok;
        k.loaded = true;
        var phone = Resources.Load<GameObject>(ResourceRoot + k.folder + k.phonePrefab);
        var phoneLens = phone != null ? phone.transform.Find(LensName) : null;
        var phoneRenderer = phoneLens != null ? phoneLens.GetComponent<MeshRenderer>() : null;
        var phoneFilter = phoneLens != null ? phoneLens.GetComponent<MeshFilter>() : null;
        k.lensMaterial = phoneRenderer != null ? phoneRenderer.sharedMaterial : null;
        k.phoneMesh = phoneFilter != null ? phoneFilter.sharedMesh : null;
        if (k.second != null)
        {
            var second = phone != null ? phone.transform.Find(k.second) : null;
            var secondRenderer = second != null ? second.GetComponent<MeshRenderer>() : null;
            var secondFilter = second != null ? second.GetComponent<MeshFilter>() : null;
            k.secondMaterial = secondRenderer != null ? secondRenderer.sharedMaterial : null;
            k.secondPhoneMesh = secondFilter != null ? secondFilter.sharedMesh : null;
        }
        foreach (var m in Resources.LoadAll<Mesh>(ResourceRoot + k.folder + k.model))
        {
            if (m == null) continue;
            if (m.name == LensName) k.lensMesh = m;
            else if (k.second != null && m.name == k.second) k.secondMesh = m;
        }
        var hasSecond = k.secondMesh != null && k.secondPhoneMesh != null && k.secondMaterial != null;
        if (!hasSecond) k.secondMesh = k.secondPhoneMesh = null;
        k.ok = k.lensMesh != null && k.phoneMesh != null && k.lensMaterial != null && (!k.secondRequired || hasSecond);
        if (!k.ok) Warn(k.folder + k.phonePrefab + ", " + k.folder + k.model);
        return k.ok;
    }

    static bool LoadDesktop(Kit k)
    {
        if (k.desktopLoaded) return k.desktopOk;
        k.desktopLoaded = true;
        var desktop = Resources.Load<GameObject>(ResourceRoot + k.folder + k.desktopPrefab);
        // A lamp's prefab holds its lens (and its second renderer) and its housing; a housing-only family's prefab is the housing.
        var housing = desktop == null ? null : k.phonePrefab != null ? desktop.transform.Find(HousingName) : desktop.transform;
        k.housingSource = housing != null && housing.GetComponent<LODGroup>() != null ? housing.gameObject : null;
        k.desktopOk = k.housingSource != null;
        if (!k.desktopOk) Warn(k.folder + k.desktopPrefab);
        return k.desktopOk;
    }

    // Lo-C: the kit library builds one Kit_WrapFixture_4ft (its materials by slot, as everywhere), the LOD0 and LOD2 meshes and
    // their material sets are kept with the lens slot on ZL_WrapLens_R1, and the probe goes before it is ever drawn.
    static bool LoadWrap()
    {
        if (wrapLoaded) return wrapOk;
        wrapLoaded = true;
        var lens = Resources.Load<Material>(ResourceRoot + WrapLensPath);
        var probe = lens != null ? FrontRoomsKitLibrary.Spawn(WrapKit, null, Vector3.zero, Quaternion.identity, null, false, "zone lamps wrap probe", false) : null;
        if (probe != null)
        {
            probe.SetActive(false);
            foreach (var r in probe.GetComponentsInChildren<MeshRenderer>(true))
            {
                var mf = r.GetComponent<MeshFilter>();
                var mesh = mf != null ? mf.sharedMesh : null;
                if (mesh == null) continue;
                if (mesh.name.EndsWith("_LOD0")) { wrapDesktop = mesh; wrapDesktopMaterials = WithLens(r.sharedMaterials, lens); }
                else if (mesh.name.EndsWith("_LOD2")) { wrapPhone = mesh; wrapPhoneMaterials = WithLens(r.sharedMaterials, lens); }
            }
            if (Application.isPlaying) Object.Destroy(probe);
            else Object.DestroyImmediate(probe);
        }
        wrapOk = wrapDesktop != null && wrapPhone != null && wrapDesktopMaterials != null && wrapPhoneMaterials != null;
        if (!wrapOk) Warn(WrapKit + ", " + WrapLensPath);
        return wrapOk;
    }

    static Material[] WithLens(Material[] set, Material lens)
    {
        var found = false;
        var copy = new Material[set.Length];
        for (var i = 0; i < set.Length; i++)
        {
            var m = set[i];
            if (m != null && m.name.StartsWith(WrapLensSlot, System.StringComparison.Ordinal)) { copy[i] = lens; found = true; }
            else copy[i] = m;
        }
        return found ? copy : null;
    }

    static void Warn(string what)
    {
        if (warned) return;
        warned = true;
        Debug.LogWarning("[FrontRoomsLampKit] Resources/" + ResourceRoot + " is incomplete (" + what + "): the lamps keep the landed kit.");
    }

    /// <summary>
    /// Builds a lamp of <paramref name="family"/> under <paramref name="parent"/> at <paramref name="position"/> /
    /// <paramref name="rotation"/> (its mounting face and axis, parent space): the lens (returned, named
    /// <paramref name="lensName"/>) and, unless <paramref name="phone"/>, the housing. Returns null and builds nothing when
    /// the kit is missing (or for a housing-only family: BuildHousing). Nothing is lit here.
    /// </summary>
    public static MeshRenderer Build(Family family, Transform parent, Vector3 position, Quaternion rotation, string lensName, bool phone)
    {
        return Build(family, parent, position, rotation, lensName, phone, out _);
    }

    /// <summary>As Build; a family with a second renderer also builds it, returned in <paramref name="second"/> (null for the
    /// others): the pendant's glow ("&lt;lensName&gt; glow", the caller writes it the lens's block), the strip's red tube
    /// ("&lt;lensName&gt; red", the caller drives its own level).</summary>
    public static MeshRenderer Build(Family family, Transform parent, Vector3 position, Quaternion rotation, string lensName, bool phone, out MeshRenderer second)
    {
        second = null;
        var name = string.IsNullOrEmpty(lensName) ? LensName : lensName;
        if (family == Family.Wrap)
        {
            if (parent == null || !LoadWrap()) return null;
            // The kit's long axis is X; turn it to run along the lamp's Z.
            return Part(parent, name, phone ? wrapPhone : wrapDesktop, phone ? wrapPhoneMaterials : wrapDesktopMaterials, position, rotation * Quaternion.Euler(0f, 90f, 0f));
        }
        var k = Get(family);
        if (parent == null || k == null || k.phonePrefab == null || !Load(k)) return null;
        if (!phone && !LoadDesktop(k)) return null;
        var lens = Part(parent, name, phone ? k.phoneMesh : k.lensMesh, new[] { k.lensMaterial }, position, rotation);
        var secondMesh = phone ? k.secondPhoneMesh : k.secondMesh;
        if (secondMesh != null)
        {
            second = Part(parent, name + k.secondSuffix, secondMesh, new[] { k.secondMaterial }, position, rotation);
            if (k.secondAdditive)
            {
                second.lightProbeUsage = LightProbeUsage.Off;
                second.reflectionProbeUsage = ReflectionProbeUsage.Off;
            }
        }
        if (!phone) Housing(k, parent, position, rotation);
        return lens;
    }

    static MeshRenderer Part(Transform parent, string name, Mesh mesh, Material[] materials, Vector3 position, Quaternion rotation)
    {
        var go = new GameObject(name);
        var t = go.transform;
        t.SetParent(parent, false);
        t.localPosition = position;
        t.localRotation = rotation;
        go.AddComponent<MeshFilter>().sharedMesh = mesh;
        var r = go.AddComponent<MeshRenderer>();
        r.sharedMaterials = materials;
        r.shadowCastingMode = ShadowCastingMode.Off;
        r.receiveShadows = false;
        return r;
    }

    /// <summary>The housing of a housing-only family (RemotePlate) under <paramref name="parent"/>: its LOD group, or null
    /// (nothing built) when the kit is missing.</summary>
    public static GameObject BuildHousing(Family family, Transform parent, Vector3 position, Quaternion rotation)
    {
        var k = Get(family);
        if (parent == null || k == null || !LoadDesktop(k)) return null;
        return Housing(k, parent, position, rotation);
    }

    static GameObject Housing(Kit k, Transform parent, Vector3 position, Quaternion rotation)
    {
        var housing = Object.Instantiate(k.housingSource, parent, false);
        housing.name = HousingName;
        housing.transform.localPosition = position;
        housing.transform.localRotation = rotation;
        housing.transform.localScale = Vector3.one;
        foreach (var r in housing.GetComponentsInChildren<Renderer>(true)) r.shadowCastingMode = ShadowCastingMode.Off;
        return housing;
    }

    // ---------------------------------------------------------------- the map's lamp per cell (MapWorld.BuildFixture)
    /// <summary>
    /// The lamp a map cell hangs (Red 2026-10-31, research/zone_lamps/40_cursor_brief.md s.2): a Low room L03, or the 4 ft
    /// wrap in a module marked back-of-house (Lo-A + Lo-C, "low zones as recommended"); an Office room of Standard height
    /// O-C's pendant (where its bottom clears PendantMinBottom under <paramref name="ceiling"/>); everything else L03 (Level 0,
    /// tall halls: H-C, "keep today's"). A family whose kit is missing gives L03.
    /// </summary>
    public static MapLamp ForCell(ZoneTheme theme, ZoneHeight height, float ceiling, bool backOfHouse)
    {
        if (height == ZoneHeight.Low) return backOfHouse && Available(Family.Wrap) ? MapLamp.Wrap : MapLamp.Troffer;
        if (theme == ZoneTheme.Office && height == ZoneHeight.Standard && ceiling - PendantDrop >= PendantMinBottom && Available(Family.Pendant))
            return MapLamp.Pendant;
        return MapLamp.Troffer;
    }

    /// <summary>The map's lamp centred on its fixture root (on the ceiling plane): the lens renderer named "Lens", and for the
    /// pendant its glow renderer ("Lens glow", else null). Null (nothing built) when the kit is missing: the map's flat lens.</summary>
    public static MeshRenderer BuildMapLamp(MapLamp lamp, Transform fixtureRoot, out MeshRenderer glow)
    {
        glow = null;
        switch (lamp)
        {
            case MapLamp.Pendant: return Build(Family.Pendant, fixtureRoot, Vector3.zero, Quaternion.identity, LensName, PhoneTier, out glow);
            case MapLamp.Wrap: return Build(Family.Wrap, fixtureRoot, Vector3.zero, Quaternion.identity, LensName, PhoneTier);
            default: return FrontRoomsTrofferKit.Build(fixtureRoot);
        }
    }

    /// <summary>The map's lens drive for its lamp: L03's (FrontRoomsTrofferKit.LensDrive: the zone lens at 1.8 as seen); the
    /// pendant's and the wrap's the zone lens's tint at their own peak (1.4, 1.8), as the option renders drove them.</summary>
    public static Color LensDrive(MapLamp lamp, Material zoneLens)
    {
        var c = FrontRoomsTrofferKit.LensDrive(zoneLens);
        if (lamp == MapLamp.Troffer) return c;
        var peak = lamp == MapLamp.Pendant ? PendantLensPeak : WrapLensPeak;
        var m = Mathf.Max(1e-4f, c.maxColorComponent);
        return new Color(c.r / m * peak, c.g / m * peak, c.b / m * peak, 1f);
    }

    /// <summary>True for a renderer that carries a lens or phone mesh of a family this kit owns (the wrap's meshes are the shared
    /// kit's, so they never count).</summary>
    public static bool IsKitLens(Renderer r)
    {
        var mf = r != null ? r.GetComponent<MeshFilter>() : null;
        var m = mf != null ? mf.sharedMesh : null;
        if (m == null) return false;
        for (var i = 0; i <= (int)Family.Pendant; i++)
        {
            var k = Get((Family)i);
            if (k != null && k.phonePrefab != null && Load(k) && (m == k.lensMesh || m == k.phoneMesh)) return true;
        }
        return false;
    }
}
