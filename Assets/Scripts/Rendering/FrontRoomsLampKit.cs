    // ---------------------------------------------------------------- metal-halide lamps (P1-A; 20_design s.6)
    /// <summary>
    /// One metal-halide lamp's state (P1-A's wall box, any HID head), kept by its caller and advanced by HidTick. The period
    /// behaviour (research/zone_lamps/10_pool.md s.7, 20_design.md s.6; the 1977-80 indirect-HID patents): the arc goes out at
    /// once when the line falls under HidDropOut; a hot lamp cannot restrike until it has cooled (minutes, compressed here to
    /// HidCool seconds); it then warms over HidWarm seconds, dim and blue-green first, white last; while it is out or warming
    /// the fixture's auxiliary quartz lamp burns, so the space never goes black ("darkness is never cover"); each lamp's white
    /// drifts (Drift, -1 greener .. 1 pinker, set once from a hash); a failing lamp cycles, out every HidCycle seconds or so.
    /// </summary>
    public struct HidLamp
    {
        /// <summary>0 out .. 1 at full output (the warm-up's progress).</summary>
        public float warm;
        /// <summary>Seconds before a restrike can begin (the hot lamp cooling).</summary>
        public float cool;
        /// <summary>The arc burns (warming or full).</summary>
        public bool arc;
        /// <summary>The lamp's colour drift, -1 (greener) .. 1 (pinker).</summary>
        public float drift;
        /// <summary>End of life: the lamp cycles.</summary>
        public bool failing;
        /// <summary>Seconds at full output before a failing lamp drops out.</summary>
        public float cycle;

        /// <summary>A lamp burning at full output (a lit room's start state).</summary>
        public static HidLamp Lit(float drift, bool failing)
        {
            return new HidLamp { warm = 1f, arc = true, drift = Mathf.Clamp(drift, -1f, 1f), failing = failing, cycle = CycleAfter(drift) };
        }

        internal static float CycleAfter(float drift) => HidCycle * (.7f + .6f * Mathf.Repeat(drift * 7.31f + .37f, 1f));
    }

    /// <summary>The line level under which the arc goes out (a deep dip), the compressed cool-down and warm-up (seconds; real
    /// lamps take 5-15 minutes to restrike), and a failing lamp's mean time at full output before it cycles out.</summary>
    public const float HidDropOut = .80f, HidCool = 8f, HidWarm = 24f, HidCycle = 45f;
    /// <summary>The restrike's first light and colour (dim, blue-green), and the drift's two ends.</summary>
    static readonly Color HidCold = new Color(.62f, .90f, 1f), HidGreen = new Color(.93f, 1f, .94f), HidPink = new Color(1f, .94f, .98f);

    /// <summary>
    /// Advances <paramref name="s"/> by <paramref name="dt"/> with the lamp's line at <paramref name="mains"/> (1 normal; the
    /// W1 dips and the C22 blackout as the map has them) and returns its output, 0..1: multiply the Light's intensity and the
    /// lens (and glow) drive by it. <paramref name="tint"/> multiplies the lamp's colour (the warm-up's blue-green, then the
    /// lamp's drift); <paramref name="auxiliary"/> is the quartz lamp's level, 0..1 (1 while the arc is out or under 60 %).
    /// </summary>
    public static float HidTick(ref HidLamp s, float mains, float dt, out Color tint, out float auxiliary)
    {
        if (s.arc && mains < HidDropOut)
        {
            s.arc = false;
            s.cool = HidCool;
            s.warm = 0f;
        }
        else if (s.arc && s.failing && s.warm >= 1f)
        {
            s.cycle -= dt;
            if (s.cycle <= 0f)
            {
                s.arc = false;
                s.cool = HidCool;
                s.warm = 0f;
                s.cycle = HidLamp.CycleAfter(s.drift + .5f);
            }
        }
        if (!s.arc)
        {
            s.cool = Mathf.Max(0f, s.cool - dt);
            if (s.cool <= 0f && mains >= HidDropOut) { s.arc = true; s.warm = 0f; }
        }
        else if (s.warm < 1f) s.warm = Mathf.Min(1f, s.warm + dt / HidWarm);
        var w = s.arc ? s.warm * s.warm * (3f - 2f * s.warm) : 0f;
        var output = s.arc ? (.05f + .95f * w) * Mathf.Clamp01(mains * mains) : 0f;
        var drifted = s.drift < 0f ? Color.Lerp(Color.white, HidGreen, -s.drift) : Color.Lerp(Color.white, HidPink, s.drift);
        tint = Color.Lerp(HidCold, Color.white, w) * drifted;
        auxiliary = s.arc ? Mathf.Clamp01((.75f - s.warm) / .15f) : 1f;
        return output;
    }

    // ---------------------------------------------------------------- high-pressure sodium lamps (Kit_WallPackHPS; G4-a)
    /// <summary>The sodium lamp's line level under which the arc goes out, its compressed hot restrike and warm-up (seconds; real HPS
    /// lamps restrike in about a minute and warm up in three to four), and an end-of-life lamp's mean time at full output before it
    /// cycles out (real cycling lamps: minutes).</summary>
    public const float HpsDropOut = .80f, HpsCool = 6f, HpsWarm = 16f, HpsCycle = 40f;
    /// <summary>The sodium lamp's colour at full output (2100 K, Ra about 24): the colour scene 4's SP5 gives its two heads.</summary>
    public static readonly Color HpsSodium = new Color(1f, .55f, .22f);
    /// <summary>The warm-up's colours: the starting gas's pink-violet glow at the strike, then mercury's pale blue before the sodium
    /// takes over (research/zone_lamps/10_other.md, 10_pool.md PL15).</summary>
    static readonly Color HpsStrike = new Color(.80f, .56f, 1f), HpsMercury = new Color(.78f, .86f, 1f);

    /// <summary>
    /// Advances a sodium lamp <paramref name="s"/> (the HidLamp state; HidLamp.Lit to start it burning) by <paramref name="dt"/> with its
    /// line at <paramref name="mains"/> and returns its output, 0..1: multiply the Light's intensity and the lens drive
    /// (WallPackLensPeak) by it. <paramref name="color"/> is the lamp's colour now (the strike's pink-violet, mercury's blue, then
    /// HpsSodium nudged by the lamp's drift), to set as the Light's colour and the lens's tint. No auxiliary lamp: a sodium head out
    /// is dark until it restrikes (the dock's own strips and heads keep the room lit; darkness is never cover). Every change is a
    /// single step (the arc out) or a ramp over seconds, never a flicker.
    /// </summary>
    public static float HpsTick(ref HidLamp s, float mains, float dt, out Color color)
    {
        if (s.arc && mains < HpsDropOut)
        {
            s.arc = false;
            s.cool = HpsCool;
            s.warm = 0f;
        }
        else if (s.arc && s.failing && s.warm >= 1f)
        {
            s.cycle -= dt;
            if (s.cycle <= 0f)
            {
                s.arc = false;
                s.cool = HpsCool;
                s.warm = 0f;
                s.cycle = HpsCycle * (.7f + .6f * Mathf.Repeat(s.drift * 5.17f + .61f, 1f));
            }
        }
        if (!s.arc)
        {
            s.cool = Mathf.Max(0f, s.cool - dt);
            if (s.cool <= 0f && mains >= HpsDropOut) { s.arc = true; s.warm = 0f; }
        }
        else if (s.warm < 1f) s.warm = Mathf.Min(1f, s.warm + dt / HpsWarm);
        var w = s.arc ? s.warm * s.warm * (3f - 2f * s.warm) : 0f;
        var output = s.arc ? (.03f + .97f * w) * Mathf.Clamp01(mains * mains) : 0f;
        var sodium = Color.Lerp(HpsSodium, new Color(1f, .60f, .27f), .5f + .5f * s.drift);
        color = w < .3f ? Color.Lerp(HpsStrike, HpsMercury, w / .3f) : Color.Lerp(HpsMercury, sodium, Mathf.Clamp01((w - .3f) / .7f));
        return output;
    }

    // ---------------------------------------------------------------- the map's lamp per cell (MapWorld.BuildFixture)
    /// <summary>
    /// The lamp a map cell hangs (Red 2026-10-31, research/zone_lamps/40_cursor_brief.md s.2): a Low room L03, or the 4 ft
    /// wrap in a module marked back-of-house (Lo-A + Lo-C, "low zones as recommended"); an Office room of Standard height
    /// O-C's pendant (where its bottom clears PendantMinBottom under <paramref name="ceiling"/>); everything else L03 (Level 0,
    /// tall halls: H-C, "keep today's"). A family whose kit is missing gives L03.
    /// </summary>
    public static MapLamp ForCell(ZoneTheme theme, ZoneHeight height, float ceiling, bool backOfHouse)
    {
        if (height == ZoneHeight.Low) return backOfHouse && Available(Family.Wrap) ? MapLamp.Wrap : MapLamp.Troffer;
        if (theme == ZoneTheme.Office && height == ZoneHeight.Standard && ceiling - PendantDrop >= PendantMinBottom && Available(Family.Pendant))
            return MapLamp.Pendant;
        return MapLamp.Troffer;
    }

    /// <summary>The map's lamp centred on its fixture root (on the ceiling plane): the lens renderer named "Lens", and for the
    /// pendant its glow renderer ("Lens glow", else null). Null (nothing built) when the kit is missing: the map's flat lens.</summary>
    public static MeshRenderer BuildMapLamp(MapLamp lamp, Transform fixtureRoot, out MeshRenderer glow)
    {
        glow = null;
        switch (lamp)
        {
            case MapLamp.Pendant: return Build(Family.Pendant, fixtureRoot, Vector3.zero, Quaternion.identity, LensName, PhoneTier, out glow);
            case MapLamp.Wrap: return Build(Family.Wrap, fixtureRoot, Vector3.zero, Quaternion.identity, LensName, PhoneTier);
            default: return FrontRoomsTrofferKit.Build(fixtureRoot);
        }
    }

    /// <summary>The map's lens drive for its lamp: L03's (FrontRoomsTrofferKit.LensDrive: the zone lens at 1.8 as seen); the
    /// pendant's and the wrap's the zone lens's tint at their own peak (1.4, 1.8), as the option renders drove them.</summary>
    public static Color LensDrive(MapLamp lamp, Material zoneLens)
    {
        var c = FrontRoomsTrofferKit.LensDrive(zoneLens);
        if (lamp == MapLamp.Troffer) return c;
        var peak = lamp == MapLamp.Pendant ? PendantLensPeak : WrapLensPeak;
        var m = Mathf.Max(1e-4f, c.maxColorComponent);
        return new Color(c.r / m * peak, c.g / m * peak, c.b / m * peak, 1f);
    }

    /// <summary>True for a renderer that carries a lens or phone mesh of a family this kit owns (the wrap's meshes are the shared
    /// kit's, so they never count).</summary>
    public static bool IsKitLens(Renderer r)
    {
        var mf = r != null ? r.GetComponent<MeshFilter>() : null;
        var m = mf != null ? mf.sharedMesh : null;
        if (m == null) return false;
        for (var i = 0; i <= (int)Family.DockArm; i++)
        {
            if (i == (int)Family.Wrap) continue;
            var k = Get((Family)i);
            if (k != null && k.phonePrefab != null && Load(k) && (m == k.lensMesh || m == k.phoneMesh)) return true;
        }
        return false;
    }

    /// <summary>
    /// The family whose lens or phone mesh <paramref name="r"/> carries, among the kits already loaded (a lens a kit built has
    /// its kit loaded), the wrap included (its LOD0 / LOD2 meshes, the shared kit's: any wrap counts). Loads nothing; false for
    /// any other renderer. LW3's lens hook reads it for the lens opening (FrontRoomsLampLens.AreaOf).
    /// </summary>
    public static bool TryFamilyOf(Renderer r, out Family family)
    {
        family = Family.Strip;
        var mf = r != null ? r.GetComponent<MeshFilter>() : null;
        var m = mf != null ? mf.sharedMesh : null;
        if (m == null) return false;
        if (wrapOk && (m == wrapDesktop || m == wrapPhone)) { family = Family.Wrap; return true; }
        if (kits == null) return false;
        for (var i = 0; i < kits.Length; i++)
        {
            var k = kits[i];
            if (k == null || !k.loaded || !k.ok) continue;
            if (m == k.lensMesh || m == k.phoneMesh) { family = (Family)i; return true; }
        }
        return false;
    }
